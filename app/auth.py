"""
Модуль аутентификации: хеширование и проверка паролей.

Студенты: этот файл демонстрирует безопасную обработку паролей.

Важно понимать разницу:
- ХЕШИРОВАНИЕ (hashing) — односторонняя функция. Пароль превращается в строку фиксированной длины.
  Невозможно "расшифровать" хеш обратно в пароль. Это стандарт для хранения паролей.
- ШИФРОВАНИЕ (encryption) — двусторонняя функция. Можно зашифровать и расшифровать.
  Используется для данных, которые нужно прочитать позже (токены, личные данные).

Почему мы используем werkzeug.security?
- generate_password_hash() по умолчанию использует PBKDF2 с солью (salt).
- Соль — случайные данные, добавляемые к паролю перед хешированием.
  Это защищает от атак "rainbow table" (предварительно вычисленных таблиц хешей).
- PBKDF2 — намеренно медленная функция, которая усложняет brute-force атаки.

Почему НЕЛЬЗЯ хранить пароли в открытом виде?
- Если злоумышленник получит доступ к БД, он увидит все пароли.
- Пользователи часто используют один пароль для нескольких сервисов.
- Это требование безопасности (GDPR, ФЗ-152 о персональных данных).
"""
from werkzeug.security import generate_password_hash, check_password_hash


def hash_password(password: str) -> str:
    """Хеширует пароль с помощью PBKDF2 + salt.

    Студенты: возвращаемая строка содержит алгоритм, соль и хеш,
    разделённые символами. Например: 'pbkdf2:sha256:260000$salt$hash'.
    Именно поэтому поле password_hash в БД имеет длину 255 символов.
    """
    return generate_password_hash(password)


def verify_password(password: str, password_hash: str) -> bool:
    """Проверяет пароль, извлекая алгоритм и соль из stored hash.

    Студенты: check_password_hash автоматически определяет, какой алгоритм
    использовался при хешировании (из stored hash строки), поэтому не нужно
    хранить алгоритм отдельно.
    """
    return check_password_hash(password_hash, password)
